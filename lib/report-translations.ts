/** Get translations for a language, falling back to English */
export function getTranslations(lang: ReportLanguage): ReportTranslations {
  return TRANSLATIONS[lang] || EN;
}

/** Get the default language for a state */
export function getDefaultLanguage(state: string): ReportLanguage {
  return STATE_LANGUAGE_MAP[state] || "en";
}

/** Get all available languages for the UI selector */
export function getAvailableLanguages(): { code: ReportLanguage; name: string; nativeName: string }[] {
  return Object.values(LANGUAGES).map(({ code, name, nativeName }) => ({ code, name, nativeName }));
}
